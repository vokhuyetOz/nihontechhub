export enum ELokiLevelLogs {
  TRACE = 'trace', //Very detailed logs (for debugging).
  DEBUG = 'debug', //Debugging information.
  INFO = 'info', //General information about application behavior.
  WARN = 'warn', //Warnings (potential issues).
  ERROR = 'error', //Errors that need attention.
  FATAL = 'fatal', //Critical issues leading to crashes.
}
